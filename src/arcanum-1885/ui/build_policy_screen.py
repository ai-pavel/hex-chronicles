#!/usr/bin/env python3
"""Build the Arcanum 1885 Social Policy screen: Brave New World's SocialPolicyPopup (tabs, ideology pane, tenets) with the
five Empires of the Smoky Skies policy branches in place of the nine stock ones. The Firaxis scenario shipped a Gods & Kings
version of this screen without ideologies; under the BNW rules the game insists on an ideology once a player is in the Modern era."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
A = os.environ.get('CIV5_ASSETS') or os.path.expanduser("~/Library/Application Support/Steam/steamapps/common/Sid Meier's Civilization V/Civilization V.app/Contents/Assets/Assets")   # the game's Assets folder
BNW = os.path.join(A, 'DLC', 'Expansion2', 'UI', 'InGame', 'Popups')
xml = open(os.path.join(BNW, 'SocialPolicyPopup.xml'), encoding='utf-8').read()
lua = open(os.path.join(BNW, 'SocialPolicyPopup.lua'), encoding='utf-8').read()
# branch ID order follows the Smoky Skies PolicyUpdate.xml rows; the texture is the one the scenario used for that branch
BRANCHES = [('CULTURE', 'Culture', 'SocialPoliciesPatronage.dds'), ('MILITARY', 'Military', 'SocialPoliciesAutocracy.dds'),
            ('INDUSTRY', 'Industry', 'SocialPoliciesOrder.dds'), ('LABOR', 'Labor', 'SocialPoliciesRationalism.dds'), ('COMMERCE', 'Commerce', 'SocialPoliciesCommerce.dds')]

def cut(s, start, end):
    i = s.index(start); j = s.index(end, i); return i, j
# ---- XML: top row = five scenario boxes built from the Tradition box template, bottom row = BNW ideology box + dim placeholders
i0, i1 = cut(xml, '<!-- TRADITION BOX  -->', '<!-- LIBERTY BOX  -->')
template = xml[i0:i1]
assert template.count('BranchButton0') == 1 and 'TraditionPanel' in template
vtrim = '<Image Anchor="R,T" Offset="0,0" Texture="VerticalTrim.dds" Size="5,290"/>'
template = template[:template.rindex(vtrim)]   # drop the trailing separator, re-added between boxes below
boxes = []
for i, (key, name, tex) in enumerate(BRANCHES):
    b = template.replace('TRADITION BOX', f'{key} BOX')
    b = b.replace('Assets/UI/Art/Icons/SocialPoliciesTradition.dds', tex).replace('SocialPoliciesTradition.dds', tex)
    b = b.replace('TXT_KEY_POLICY_BRANCH_TRADITION_HELP', f'TXT_KEY_STEAMPUNK_SCENARIO_VICTORY_CATEGORY_{key}')
    b = b.replace('TXT_KEY_POLICY_BRANCH_TRADITION_CAP', f'TXT_KEY_STEAMPUNK_SCENARIO_VICTORY_CATEGORY_{key}')
    b = b.replace('TraditionPanel', f'{name}Panel')
    b = re.sub(r'(ID="(?:BranchBack|ImageMask|DisabledMask|LockedBox|BranchButton|DisabledBox|Lock|EraLabel))0"', lambda m: m.group(1) + f'{i}"', b)
    assert f'BranchButton{i}' in b and f'Lock{i}"' in b and f'{name}Panel' in b
    boxes.append(b)
top_row = ('\n' + vtrim + '\n').join(boxes)
t0, t1 = cut(xml, '<!-- TRADITION BOX  -->', '<!-- BOTTOM ROW')
closing = xml[xml.rindex('</Stack>', t0, t1):t1]   # "</Stack>\n\t\t\t\t\t" that closes the top-row stack
xml2 = xml[:t0] + top_row + '\n\t\t\t\t\t' + closing + xml[t1:]
# bottom row: keep the ideology box, replace the four stock branch boxes with dim placeholders (the scenario's look)
b0 = xml2.index('<!-- RATIONALISM BOX  -->'); b1 = xml2.index('<!-- End bottom row -->')
tail = xml2[xml2.rindex('</Stack>', b0, b1):b1]   # closes the bottom-row stack, then the HorizontalTrim line
placeholder = '<Box Size="190,290 " Anchor="C,T" Color="0,0,0,0">\n\t\t\t\t\t\t\t<Image Anchor="C,T" Offset="0,0" Size="190,290" Color="255,255,255,50" Texture="SocialPoliciesLiberty.dds"/>\n\t\t\t\t\t\t</Box>'
bottom = ('\n' + vtrim + '\n').join([placeholder] * 4)
xml2 = xml2[:b0] + '<!-- empty slots -->\n\t\t\t\t\t\t' + bottom + '\n\t\t\t\t\t' + tail + xml2[b1:]
for stock in ('TraditionPanel', 'LibertyPanel', 'HonorPanel', 'PietyPanel', 'PatronagePanel', 'RationalismPanel', 'ExplorationPanel', 'AestheticsPanel', 'BranchButton5', 'BranchButton8'):
    assert stock not in xml2, stock
header = '<!-- Arcanum 1885: Brave New World social policy screen with the five Empires of the Smoky Skies branches. Generated by build_policy_screen.py. -->\n'
xml2 = xml2.replace('<Context ', header + '<Context ', 1)
open(os.path.join(HERE, 'SocialPolicyPopup.xml'), 'w', encoding='utf-8').write(xml2)

# ---- Lua: swap the nine per-branch instance managers for five, keep every ideology feature
def rep(s, old, new, count=1):
    assert s.count(old) == count, (old[:60], s.count(old))
    return s.replace(old, new)
m0 = lua.index('local g_LibertyPipeManager'); m1 = lua.index('local g_TenetInstanceManager')
managers = ''.join(f'local g_{n}PipeManager = InstanceManager:new( "ConnectorPipe", "ConnectorImage", Controls.{n}Panel );\n' for _, n, _ in BRANCHES) + '\n' + \
           ''.join(f'local g_{n}InstanceManager = InstanceManager:new( "PolicyButton", "PolicyIcon", Controls.{n}Panel );\n' for _, n, _ in BRANCHES) + '\n'
lua2 = lua[:m0] + managers + lua[m1:]
def chain(var):
    return ''.join(('\tif' if k == 0 else '\telseif') + f' branchType == "POLICY_BRANCH_{key}" then\n\t\tcontrolTable = g_{n}{var}:GetInstance();\n' for k, (key, n, _) in enumerate(BRANCHES)) + '\tend\n'
p0 = lua2.index('function GetPipe(branchType)'); p1 = lua2.index('\treturn controlTable;', p0)
lua2 = lua2[:p0] + 'function GetPipe(branchType)\n\tlocal controlTable = nil;\n' + chain('PipeManager') + lua2[p1:]
q0 = lua2.index('-- decide which panel it goes on', lua2.index('-- Add Policy buttons')); q1 = lua2.index('if (controlTable ~= nil) then', q0)
lua2 = lua2[:q0] + '-- decide which panel it goes on\n\t\t\tlocal branchType = iBranch;\n' + chain('InstanceManager').replace('\tif', '\t\t\tif').replace('\telseif', '\t\t\telseif').replace('\t\tcontrolTable', '\t\t\t\tcontrolTable').replace('\tend\n', '\t\t\tend\n') + '\t\t\t' + lua2[q1:]
lua2 = rep(lua2, '\tprint ("In UpdateDisplay()");\n', '')
# the scenario branches carry a generic title key; guard against a missing one instead of erroring
lua2 = rep(lua2, 'local strTextKey = GameInfo.PolicyBranchTypes[iDominantBranch].Title;', 'local strTextKey = GameInfo.PolicyBranchTypes[iDominantBranch].Title or "TXT_KEY_LEADER_OF_CIV";')
assert 'g_LibertyInstanceManager' not in lua2 and 'POLICY_BRANCH_RATIONALISM' not in lua2 and 'g_TenetInstanceManager' in lua2 and 'function TenetSelect' in lua2
lua2 = '-- Arcanum 1885: Brave New World social policy screen (tabs, ideologies, tenets) with the five Empires of the Smoky Skies\n-- branches instead of the nine stock ones. Generated from the game\'s DLC/Expansion2 file by build_policy_screen.py.\n' + lua2
open(os.path.join(HERE, 'SocialPolicyPopup.lua'), 'w', encoding='utf-8').write(lua2)
print('wrote SocialPolicyPopup.xml', len(xml2), 'and SocialPolicyPopup.lua', len(lua2))
