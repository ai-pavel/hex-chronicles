def build(config):
    site = config["site"]
    mods = [load_mod(entry) for entry in config["mods"]]

    if PUBLIC.exists():
        shutil.rmtree(PUBLIC)
    (PUBLIC / "assets").mkdir(parents=True)
    for name in ("style.css", "site.js"):
        shutil.copy(SITE / "assets" / name, PUBLIC / "assets" / name)
    (PUBLIC / "assets" / "favicon.svg").write_text(FAVICON)

    for mod in mods:
        dest = PUBLIC / "mods" / mod["slug"]
        (dest / "screens").mkdir(parents=True)
        resized(mod["cover"], dest / "cover.jpg", 1024, quality=88)
        resized(mod["cover"], dest / "cover-640.jpg", 640)
        resized(mod["cover"], dest / "cover-192.jpg", 192, quality=80)
        shots = []
        for shot in mod["screens"]:
            resized(shot, dest / "screens" / shot.name, 1920, quality=86)
            shots.append((shot.name, resized(shot, dest / "screens" / f"thumb-{shot.name}", 640, quality=80)))
        write_zip(mod["package"], dest / mod["zip_name"])
        zip_size = mod["zip_size"] = (dest / mod["zip_name"]).stat().st_size
        (dest / "index.html").write_text(mod_page(site, mod, zip_size, shots), encoding="utf-8")
        print(f'{mod["title"]}: v{mod["version"]}, {len(shots)} images, {mod["zip_name"]} {human_size(zip_size)}')

    soon = [dict(entry, soon=True) for entry in config.get("soon", [])]
    svg = world_map([mod for mod in mods if mod.get("map")] + soon)
    (PUBLIC / "index.html").write_text(index_page(site, mods, map_section(mods, soon, svg)), encoding="utf-8")
    (PUBLIC / "404.html").write_text(not_found_page(site), encoding="utf-8")
    (PUBLIC / "robots.txt").write_text(f'User-agent: *\nAllow: /\nSitemap: {site["url"]}sitemap.xml\n')
    urls = [site["url"]] + [f'{site["url"]}mods/{m["slug"]}/' for m in mods]
    (PUBLIC / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "".join(f"  <url><loc>{u}</loc></url>\n" for u in urls) + "</urlset>\n")
    print(f"site written to {PUBLIC}")


KEEP_PACKAGES = 3   # site versions kept in the Package Registry; older ones are deleted after a deploy


def glab(endpoint, method=None, body=None, raw=None, paginate=False):
    """Call the GitLab API through glab, which holds the credentials; returns the parsed JSON (or None)."""
    cmd = ["glab", "api", endpoint]
    if method: cmd += ["--method", method]
    if paginate: cmd += ["--paginate"]
    with tempfile.TemporaryDirectory() as tmp:
        if body is not None:
            path = Path(tmp) / "body.json"; path.write_text(json.dumps(body))
            cmd += ["--input", str(path)]
        if raw is not None:
            cmd += ["--header", "Content-Type: application/octet-stream", "--input", str(raw)]
        out = subprocess.run(cmd, check=True, text=True, capture_output=True).stdout.strip()
    if not out: return None
    if paginate and out.startswith("[") and "][" in out: out = out.replace("][", ",")
    return json.loads(out)


def pack_site():
    path = OUT / "site.tar.gz"
    with tarfile.open(path, "w:gz") as tar:
        for f in sorted(PUBLIC.rglob("*")):
            if f.is_file(): tar.add(f, arcname=str(f.relative_to(PUBLIC)))
    return path


def upload_mods(pid, config):
    """Each mod's zip as a generic package of its own (name = slug, version = mod version), skipped if already there."""
    for entry in config["mods"]:
        slug = entry["slug"]
        for zf in sorted((PUBLIC / "mods" / slug).glob("*-v*.zip")):
            version = re.search(r"-v(\d+)\.zip$", zf.name).group(1)
            digest = hashlib.sha256(zf.read_bytes()).hexdigest()
            existing = glab(f"projects/{pid}/packages?package_type=generic&package_name={slug}&per_page=100") or []
            same = [pk for pk in existing if pk["name"] == slug and pk["version"] == version]
            if same:
                files = glab(f"projects/{pid}/packages/{same[0]['id']}/package_files") or []
                if any(f["file_name"] == zf.name and f.get("file_sha256") == digest for f in files):
                    print(f"{slug} {version}: already in the Package Registry")
                    continue
            glab(f"projects/{pid}/packages/generic/{slug}/{version}/{zf.name}", method="PUT", raw=zf)
            print(f"{slug} {version}: uploaded {zf.name} to the Package Registry")


def deploy(config):
    project = config["site"]["project"]
    pid = glab(f"projects/{urllib.parse.quote(project, safe='')}")["id"]
    version = time.strftime("%Y%m%d.%H%M%S")
    archive = pack_site()
    glab(f"projects/{pid}/packages/generic/site/{version}/site.tar.gz", method="PUT", raw=archive)
    print(f"uploaded site {version} ({archive.stat().st_size / 1024 / 1024:.1f} MB) to the Package Registry of {project}")

    # the repository keeps only the CI job, the README and the version pointer; anything else (the old committed site) goes
    tree = glab(f"projects/{pid}/repository/tree?recursive=true&per_page=100", paginate=True) or []
    present = {e["path"] for e in tree if e["type"] == "blob"}
    wanted = {".gitlab-ci.yml": CI_YML, "README.md": OUT_README, "SITE_VERSION": version + "\n"}
    actions = [{"action": "update" if f in present else "create", "file_path": f, "content": c} for f, c in wanted.items()]
    actions += [{"action": "delete", "file_path": f} for f in sorted(present - set(wanted))]
    branch = glab(f"projects/{pid}")["default_branch"]
    commit = glab(f"projects/{pid}/repository/commits", method="POST",
                  body={"branch": branch, "commit_message": f"Publish site {version}", "actions": actions})
    print(f"committed {commit['short_id']} (SITE_VERSION {version}, {len(present - set(wanted))} old files removed); the Pages job runs now")

    upload_mods(pid, config)

    packages = glab(f"projects/{pid}/packages?package_type=generic&package_name=site&order_by=created_at&sort=desc&per_page=100") or []
    for old in [p for p in packages if p["name"] == "site"][KEEP_PACKAGES:]:
        glab(f"projects/{pid}/packages/{old['id']}", method="DELETE")
        print(f"deleted old site package {old['version']}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--deploy", action="store_true", help="upload the built site to GitLab and publish it")
    args = parser.parse_args()
    config = json.loads((SITE / "mods.json").read_text(encoding="utf-8"))
    build(config)
    if args.deploy:
        deploy(config)


if __name__ == "__main__":
    main()
