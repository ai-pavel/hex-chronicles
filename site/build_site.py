# ---------------------------------------------------------------------------------------------------------- the mods

def read_description(slug):
    """The BBCode block under '## Description' in the mod's PUBLISH.md."""
    text = (ROOT / "src" / slug / "publish" / "PUBLISH.md").read_text(encoding="utf-8")
    m = re.search(r"^## Description.*?\n```\n(.*?)\n```", text, re.S | re.M)
    if not m:
        raise SystemExit(f"{slug}: no Description block in PUBLISH.md")
    return m.group(1)


def inline(text):
    text = html.escape(text, quote=False).replace("-&gt;", "→")
    text = re.sub(r"\[b\](.*?)\[/b\]", r"<strong>\1</strong>", text, flags=re.S)
    return re.sub(r"\[i\](.*?)\[/i\]", r"<em>\1</em>", text, flags=re.S)


def parse_description(bbcode):
    """Title, lead paragraphs and [(heading, [paragraph html])] sections of a Workshop description."""
    title, lead, sections = None, [], []
    for block in re.split(r"\n\s*\n", bbcode.strip()):
        lines = [line.strip() for line in block.strip().splitlines()]
        if lines[0].startswith("[h1]"):
            title = re.sub(r"\[/?h1\]", "", lines[0])
            lines = lines[1:]
            if not lines:
                continue
        heading = re.fullmatch(r"\[b\](.*?)\[/b\]", lines[0])
        if heading:
            sections.append((heading.group(1), []))
            lines = lines[1:]
            if not lines:
                continue
        para = inline(" ".join(lines))
        (sections[-1][1] if sections else lead).append(para)
    if not title:
        raise SystemExit("description without [h1] title")
    return title, lead, sections


def find_package(title):
    """The newest dist/<title> (v N).civ5mod."""
    found = []
    for path in (ROOT / "dist").glob(f"{title} (v *).civ5mod"):
        m = re.fullmatch(re.escape(title) + r" \(v (\d+)\)\.civ5mod", path.name)
        if m:
            found.append((int(m.group(1)), path))
    if not found:
        raise SystemExit(f"no dist/{title} (v N).civ5mod: run tools/pack_civ5mod.py first")
    return max(found)


def write_zip(package, dest):
    """A zip holding just the .civ5mod, with a fixed timestamp so that an unchanged package gives an identical zip."""
    info = zipfile.ZipInfo(package.name, date_time=(2026, 1, 1, 0, 0, 0))
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o644 << 16
    with zipfile.ZipFile(dest, "w") as zf:
        zf.writestr(info, package.read_bytes(), compresslevel=9)


def resized(src, dest, width, quality=84):
    with Image.open(src) as im:
        im = im.convert("RGB")
        if im.width > width:
            im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
        im.save(dest, "JPEG", quality=quality, optimize=True, progressive=True)
        return im.size


def human_size(n):
    return f"{n / 1024 / 1024:.1f} MB" if n >= 1024 * 1024 else f"{n / 1024:.0f} KB"


def load_mod(entry):
    slug = entry["slug"]
    pub = ROOT / "src" / slug / "publish"
    title, lead, sections = parse_description(read_description(slug))
    version, package = find_package(title)
    changelog = " ".join(p for h, ps in sections if h == "Changelog" for p in ps)
    m = re.search(rf"v{version} \((\d{{4}}-\d{{2}}-\d{{2}})\)", changelog)
    dates = re.findall(r"v\d+ \((\d{4}-\d{2}-\d{2})\)", changelog)        # every version's date in the changelog
    return dict(entry, title=title, lead=lead, sections=sections, version=version, package=package,
                released=m.group(1) if m else None, first_release=min(dates, default=""),
                updated=(m.group(1) if m else max(dates, default="")), cover=pub / "cover.jpg",
                screens=sorted((pub / "screens").glob("*.jpg")),
                zip_name=f"{title.replace(' ', '-')}-v{version}.zip")


# ---------------------------------------------------------------------------------------------------------- the world map
# A hex map of the world on the index page: every mod with a "map" entry in mods.json (released mods and the "soon" list)
# lights its region. A region is Natural Earth countries (ADM0_A3) and/or first-level regions ([ADM0_A3, name]), cut to a
# lon/lat box; "islands" lights the hex nearest to every island even if it covers too little of a hex to count.
# The map is meant to read like a game's world map, not an atlas plate: Miller cylindrical projection (the classic wall
# map, roomy in the northern mid-latitudes), pointy-top hexes in odd-row offset like the game's, 14 x 16 SVG units each so
# that every corner is an integer; drawn as one <path> per set of mods covering the same hexes. Seas and islands win over
# accuracy (see world_map): a hex is land only if most of it is, separate land masses never touch, every island of some
# size keeps a hex and the straits in MAP_SEA stay open.

MAP_W = 190                        # hexes across the world
MAP_LAT = (-56.0, 78.0)            # Cape Horn to Svalbard; Antarctica is left out
MAP_HEX = [(0, -8), (7, -4), (7, 4), (0, 8), (-7, 4), (-7, -4)]
MAP_LAND = 0.5                     # the share of a hex that must be land
MAP_ISLAND = 1500                  # km²: a land polygon this big keeps at least one hex
MAP_MINOR = 5000                   # km²: a smaller island touching other land joins that coast instead of a strait
# Big islands that sit in a river mouth or behind channels too narrow to show: they join the mainland's coast like an islet
# instead of opening a strait (Marajo split the Amazon mouth into a bay with an island in it).
MAP_JOIN = {"Marajó": (-49.6, -0.9)}
# Narrow seas that the hexes would close otherwise, and the straits that make Scandinavia and the Mediterranean read: every
# hex a line through these (lon, lat) points passes nearest to is sea. Straits between separate land masses (the Channel,
# the Irish Sea, Korea, Bering, Malacca...) open by themselves; these are the ones within a single Natural Earth polygon.
MAP_SEA = {
    "Skagerrak": [(7.5, 57.9), (10.5, 58.1)],
    "Kattegat and the Øresund": [(11.3, 57.5), (11.8, 56.5), (12.7, 55.7)],
    "the Baltic Sea": [(14.5, 55.2), (17.0, 56.3), (19.5, 57.8), (20.5, 59.3)],
    "the Gulf of Bothnia": [(19.8, 60.5), (20.2, 62.5), (21.8, 64.3), (23.5, 65.4)],
    "the Gulf of Finland": [(22.0, 59.7), (27.5, 60.1)],
    "Gibraltar": [(-6.0, 35.95), (-5.2, 36.0)],
    "Dardanelles, Marmara and the Bosporus": [(26.3, 40.1), (28.0, 40.7), (29.1, 41.2)],
    "the Red Sea and Bab-el-Mandeb": [(34.0, 28.0), (35.5, 26.5), (37.5, 23.5), (39.5, 20.0), (41.5, 16.0), (43.4, 12.6)],
    "the Persian Gulf and Hormuz": [(48.5, 29.7), (50.5, 27.5), (52.5, 26.3), (55.0, 26.2), (56.4, 26.4), (57.5, 25.3)],
    "the Gulf of California": [(-114.6, 31.2), (-112.5, 28.5), (-110.0, 25.0), (-108.5, 23.0)],
}


def miller(lon, lat):
    """Miller cylindrical projection of degree arrays, unit sphere, y up."""
    return np.radians(lon), 1.25 * np.log(np.tan(np.pi / 4 + 0.4 * np.radians(lat)))


def polygons(geometry):
    """Outer and inner rings of a GeoJSON (Multi)Polygon; Antarctica's ring that wraps the pole is dropped."""
    if geometry is None:
        return []
    polys = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
    return [p for p in polys if np.ptp(np.asarray(p[0])[:, 0]) < 300]


def km2(poly):
    """Rough area of a polygon's outer ring, enough to rank islands."""
    ring = np.radians(np.asarray(poly[0], float))
    x, y = ring[:, 0] * np.cos(ring[:, 1]) * 6371, ring[:, 1] * 6371
    return abs(np.dot(x, np.roll(y, 1)) - np.dot(y, np.roll(x, 1))) / 2


def world_map(entries):
    """The map as SVG markup, for the mods in entries (dicts with slug, title, period, soon, map)."""
    data = Path(os.environ.get("HEX_DATA", ROOT / "data"))   # tools/fetch_data.py, as for the map generators
    files = {name: data / f"ne_10m_{name}.geojson" for name in ("land", "admin_0_countries", "admin_1_states_provinces")}
    for path in files.values():
        if not path.exists():
            raise SystemExit(f"{path} missing: run tools/fetch_data.py or set HEX_DATA")
    feats = {name: json.loads(path.read_text(encoding="utf-8"))["features"] for name, path in files.items()}

    x0, _ = miller(-180.0, 0.0)
    _, y0 = miller(0.0, MAP_LAT[1])
    _, y1 = miller(0.0, MAP_LAT[0])
    scale = 14 * MAP_W / (-2 * x0)                       # SVG units per projected unit
    rows = int((y0 - y1) * scale - 16) // 12 + 1
    width, height = 14 * MAP_W + 7, 12 * (rows - 1) + 16

    def to_svg(lon, lat):
        x, y = miller(np.asarray(lon, float), np.clip(np.asarray(lat, float), -89, 89))
        return (x - x0) * scale, (y0 - y) * scale

    def raster(polys, ids=None):
        """One pixel per SVG unit: a boolean mask, or with ids the id of the polygon under each pixel (0 for none)."""
        img = Image.new("I" if ids else "1", (width, height), 0)
        draw = ImageDraw.Draw(img)
        for n, poly in enumerate(polys):
            for k, ring in enumerate(poly):
                ring = np.asarray(ring, float)
                sx, sy = to_svg(ring[:, 0], ring[:, 1])
                draw.polygon(list(zip(sx.tolist(), sy.tolist())), fill=0 if k else (ids[n] if ids else 1))
        return np.array(img, np.int32 if ids else bool)

    # hex centres and the sample points inside each hex
    col, row = np.meshgrid(np.arange(MAP_W), np.arange(rows))
    cx = (14 * col + 7 + 7 * (row & 1)).ravel()
    cy = (12 * row + 8).ravel()
    offsets = [(dx, dy) for dx in range(-6, 7, 2) for dy in range(-7, 8, 2) if abs(dy) <= 8 - abs(dx) * 4 / 7]
    px = np.clip(cx[:, None] + np.array([o[0] for o in offsets]), 0, width - 1)
    py = np.clip(cy[:, None] + np.array([o[1] for o in offsets]), 0, height - 1)
    # the six neighbours, as pairs of hex indices (each pair once): east, south-west and south-east
    r, c = row.ravel(), col.ravel()
    pairs = []
    for dr, dc_even, dc_odd in ((0, 1, 1), (1, -1, 0), (1, 0, 1)):
        nc, nr = c + np.where(r & 1, dc_odd, dc_even), r + dr
        ok = (nc >= 0) & (nc < MAP_W) & (nr < rows)
        pairs += zip(np.flatnonzero(ok).tolist(), (nr * MAP_W + nc)[ok].tolist())

    def cover(mask):
        return mask[py, px].mean(axis=1)

    def nearest(lon, lat):
        sx, sy = to_svg(lon, lat)
        return int(np.argmin((cx - sx) ** 2 + (cy - sy) ** 2))

    # Land: every land polygon gets an id (1 = the biggest); a hex is land if most of its samples are, and belongs to the
    # polygon most of its land samples fall in. Drawn biggest first, so that an island in a lake stays an island.
    masses = sorted((p for f in feats["land"] for p in polygons(f["geometry"])), key=km2, reverse=True)
    area = np.array([0.0] + [km2(p) for p in masses])
    ids = raster(masses, list(range(1, len(masses) + 1)))
    joined = set()
    for lon, lat in MAP_JOIN.values():
        jx, jy = to_svg(lon, lat)
        if ids[int(jy), int(jx)]:
            joined.add(int(ids[int(jy), int(jx)]))
    samples = ids[py, px]
    land = (samples > 0).mean(axis=1)
    mass = np.zeros(len(cx), int)
    for i in np.flatnonzero(land >= MAP_LAND):
        mass[i] = np.bincount(samples[i][samples[i] > 0]).argmax()
    # every island above MAP_ISLAND without a hex of its own takes the sea hex nearest its middle (within a hex)
    count = np.bincount(mass, minlength=len(masses) + 1)
    flat = ids.ravel()
    pixels = np.bincount(flat, minlength=len(masses) + 1)
    sx = np.bincount(flat, weights=np.tile(np.arange(width), height), minlength=len(masses) + 1)
    sy = np.bincount(flat, weights=np.repeat(np.arange(height), width), minlength=len(masses) + 1)
    for m in range(1, len(masses) + 1):
        if area[m] < MAP_ISLAND or count[m]:
            continue
        if pixels[m]:
            mx, my = sx[m] / pixels[m], sy[m] / pixels[m]
        else:
            ring = np.asarray(masses[m - 1][0], float)
            mx, my = to_svg(ring[:, 0].mean(), ring[:, 1].mean())
        d = (cx - mx) ** 2 + (cy - my) ** 2
        for i in np.argsort(d, kind="stable")[:3]:
            if d[i] <= 16 ** 2 and not mass[i]:
                mass[i] = m
                break
    # separate land masses never touch: where two meet, the bigger one's hex goes under water so that a strait shows (the
    # Channel, Ireland, Sicily, Sri Lanka, Japan...), unless the smaller is a mere islet (under MAP_MINOR) or the bigger
    # would be left with less than three hexes (Corsica and Sardinia): then the smaller joins the bigger one's coast
    count = np.bincount(mass, minlength=len(masses) + 1)
    changed = True
    while changed:
        changed = False
        for a, b in pairs:
            ma, mb = mass[a], mass[b]
            if not ma or not mb or ma == mb:
                continue
            small, big = (a, b) if (area[ma], -ma) < (area[mb], -mb) else (b, a)
            if area[mass[small]] < MAP_MINOR or mass[small] in joined or count[mass[big]] < 4:
                count[mass[small]] -= 1
                count[mass[big]] += 1
                mass[small] = mass[big]
            else:
                count[mass[big]] -= 1
                mass[big] = 0
            changed = True
    for points in MAP_SEA.values():
        for (lon0, lat0), (lon1, lat1) in zip(points, points[1:] or points):
            for t in np.linspace(0, 1, 40):
                mass[nearest(lon0 + (lon1 - lon0) * t, lat0 + (lat1 - lat0) * t)] = 0
    shown = mass > 0
    zones = {}                                           # slug -> set of hex indices
    for entry in entries:
        spec = entry["map"]
        lon0, lat0, lon1, lat1 = spec.get("box", (-180, -90, 180, 90))
        regions = {tuple(r) for r in spec.get("regions", [])}
        polys = [p for f in feats["admin_0_countries"] if f["properties"]["ADM0_A3"] in spec.get("countries", [])
                 for p in polygons(f["geometry"])]
        polys += [p for f in feats["admin_1_states_provinces"] for p in polygons(f["geometry"])
                  if {(f["properties"]["adm0_a3"], f["properties"]["name"]),
                      (f["properties"]["adm0_a3"], f["properties"]["name_en"])} & regions]
        if not polys:
            raise SystemExit(f'{entry["slug"]}: the map entry in mods.json matches nothing in Natural Earth')
        box = [[(lon0 + (lon1 - lon0) * i / 100, lat0) for i in range(101)] +
               [(lon1 - (lon1 - lon0) * i / 100, lat1) for i in range(101)]]
        part = cover(raster(polys) & raster([box]))
        hexes = set(np.flatnonzero(shown & (part >= 0.25) & (part >= 0.5 * land)).tolist())
        # islands (or a region too small for any hex) light the hex nearest to their middle
        inside = []
        for poly in polys:
            ring = np.asarray(poly[0], float)
            lon, lat = ring[:, 0].mean(), ring[:, 1].mean()
            if lon0 <= lon <= lon1 and lat0 <= lat <= lat1:
                inside.append((len(ring), lon, lat))
        if spec.get("islands"):
            hexes |= {nearest(lon, lat) for n, lon, lat in inside if n >= 20}
        # "points": lon/lat spots whose nearest hex belongs to the region whatever the share (a thin coastal strip)
        hexes |= {nearest(lon, lat) for lon, lat in spec.get("points", [])}
        if not hexes:
            hexes.add(nearest(*max(inside)[1:]))
        zones[entry["slug"]] = hexes

    # each lit hex goes to the set of mods covering it, most specific (smallest region) first
    by_slug = {e["slug"]: e for e in entries}
    order = sorted(zones, key=lambda s: (len(zones[s]), s))
    lit = sorted(set().union(*zones.values()))
    # a hex names only the scenarios of the colour it is drawn in: a coming-soon region inside a released mod's map
    # shows only the coming-soon scenarios
    groups = {}
    for i in lit:
        covering = [s for s in order if i in zones[s]]
        soon = bool(by_slug[covering[0]].get("soon"))
        groups.setdefault(tuple(s for s in covering if bool(by_slug[s].get("soon")) == soon), []).append(i)
    shown[lit] = False
    # the picture is cut to the hexes drawn, so that the empty ocean at the sides does not shrink the land
    used = np.flatnonzero(shown).tolist() + lit
    left, right = int(cx[used].min()) - 8, int(cx[used].max()) + 8
    top, bottom = int(cy[used].min()) - 9, int(cy[used].max()) + 9

    def path(hexes):
        return "".join(f"M{cx[i]} {cy[i] - 8}l7 4v8l-7 4-7-4v-8z" for i in hexes)

    parts = [f'<path class="land" d="{path(np.flatnonzero(shown))}"/>']
    slugs = [e["slug"] for e in entries]                 # mods.json order, also the order of the Tab stops
    for key in sorted(groups, key=lambda k: (slugs.index(k[0]), len(k))):
        status = "soon" if by_slug[key[0]].get("soon") else "released"
        label = "; ".join(f'{by_slug[s]["title"]}' + (" (coming soon)" if by_slug[s].get("soon") else "") for s in key)
        attrs = f'class="zone {status}" data-mods="{" ".join(key)}" aria-label="{html.escape(label)}"'
        shape = f'<path d="{path(groups[key])}"/>'
        # a click opens the scenario the hexes are coloured for, never a bigger one behind it
        if status == "released":
            parts.append(f'<a href="mods/{key[0]}/" {attrs}>{shape}</a>')
        else:
            parts.append(f'<g tabindex="0" role="img" {attrs}>{shape}</g>')
        print(f'map: {" + ".join(key)}: {len(groups[key])} hexes')
    info = {e["slug"]: {"title": e["title"], "period": e["period"], "soon": bool(e.get("soon"))} for e in entries}
    print(f"map: {MAP_W} x {rows} hexes, {int(shown.sum())} neutral land, {len(lit)} lit")
    return (f'<svg class="hexmap" viewBox="{left} {top} {right - left} {bottom - top}" tabindex="-1" role="group" aria-label="World map of the scenarios">\n'
            + "\n".join(parts) + "\n</svg>\n"
            + f'<script type="application/json" id="map-mods">{json.dumps(info, ensure_ascii=False)}</script>')


