def support_section():
    """The donation section of the index page, from site/donations.json (links and crypto addresses; empty ones skipped)."""
    path = SITE / "donations.json"
    data = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    links = [l for l in data.get("links", []) if l.get("url", "").strip()]
    crypto = [c for c in data.get("crypto", []) if c.get("address", "").strip()]
    if not links and not crypto:
        return ""
    out = ['<section class="support-section" id="support" aria-labelledby="support-title">',
           '<div class="section-head"><h2 id="support-title">Support</h2></div>',
           '<p class="lead">The mods are made for fun, and free. If you enjoy them and want to help, thank you!</p>']
    if links:
        out.append('<div class="support-links">' + "".join(
            f'<a class="button" href="{html.escape(l["url"].strip())}" rel="noopener">{html.escape(l["name"])}</a>' for l in links) + "</div>")
    if crypto:
        out.append('<div class="support">')
        for coin in crypto:
            address = html.escape(coin["address"].strip())
            symbol = coin.get("symbol", "").strip()
            symbol_html = f' <span class="symbol">({html.escape(symbol)})</span>' if symbol else ""
            # the copy button stays hidden until site.js shows it, so the page makes sense without scripts
            out.append(f'<div class="wallet"><h3>{html.escape(coin["name"])}{symbol_html}</h3><div class="address"><code>{address}</code>'
                       f'<button class="copy" type="button" data-copy="{address}" hidden>Copy</button></div></div>')
        out.append("</div>")
    out.append("</section>")
    return "\n".join(out) + "\n"


def sort_year(mod):
    """The year a scenario starts, for the Date sort: the number in its title (Spain 1936, Arcanum 1885)."""
    m = re.search(r"\d{3,4}", mod["title"])
    return int(m.group()) if m else 0


